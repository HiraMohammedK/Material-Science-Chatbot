def fetch_arxiv_papers(keywords, max_results=50):
    base_url = 'http://export.arxiv.org/api/query?'
    all_papers = []

    for symbol, name in tqdm(ELEMENTS.items(), desc="Fetching arXiv papers"):
        query = f'all:"{name}" OR all:"{symbol}"'
        params = {
            'search_query': query,
            'start': 0,
            'max_results': max_results,
            'sortBy': 'relevance',
            'sortOrder': 'descending'
        }

        try:
            response = requests.get(base_url, params=params)
            feed = feedparser.parse(response.content)

            for entry in feed.entries:
                paper_data = {
                    'title': entry.title,
                    'authors': [author.name for author in entry.authors],
                    'abstract': entry.summary,
                    'published': entry.published,
                    'pdf_url': None,
                    'source': 'arXiv'
                }

                for link in entry.links:
                    if link.type == 'application/pdf':
                        paper_data['pdf_url'] = link.href.replace('http://', 'https://')
                        break

                all_papers.append(paper_data)

            time.sleep(1)
        except Exception as e:
            print(f"Error for {symbol}: {e}")
            continue

    df = pd.DataFrame(all_papers)
    df.to_csv('/content/data/papers/arxiv_papers.csv', index=False)
    print(f"Saved {len(df)} arXiv papers")
    return df

