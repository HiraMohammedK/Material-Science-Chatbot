class MatSciBERTEmbeddings:
    def __init__(self, model_path: str, device: str = None, whiten: bool = False):
        self.device = device or ('cuda' if torch.cuda.is_available() else 'cpu')
        self.tokenizer = AutoTokenizer.from_pretrained(model_path)
        self.model = AutoModel.from_pretrained(model_path, output_hidden_states=True).to(self.device)
        self.model.eval()
        self.whiten = whiten
        self.pca = None

    def _compute_embeddings(self, texts):
        inputs = self.tokenizer(
            texts,
            padding=True,
            truncation=True,
            return_tensors="pt",
            max_length=512
        )
        inputs = {k: v.to(self.device) for k, v in inputs.items()}

        with torch.no_grad():
            outputs = self.model(**inputs)
            hidden_states = outputs.hidden_states

        # Take [CLS] token from last two layers
        cls_last = hidden_states[-1][:, 0, :]
        cls_second = hidden_states[-2][:, 0, :]
        embeddings = (cls_last + cls_second) / 2.0

        return embeddings.cpu().numpy()

    def embed_documents(self, texts, batch_size=16):
        all_embs = []
        for i in range(0, len(texts), batch_size):
            batch_texts = texts[i:i+batch_size]
            embs = self._compute_embeddings(batch_texts)
            all_embs.append(embs)

        all_embs = np.vstack(all_embs)

        if self.whiten:
            if self.pca is None:
                self.pca = PCA(whiten=True)
                all_embs = self.pca.fit_transform(all_embs)
            else:
                all_embs = self.pca.transform(all_embs)

        norms = np.linalg.norm(all_embs, axis=1, keepdims=True)
        norms[norms == 0] = 1.0
        all_embs = all_embs / norms

        return all_embs.tolist()

    def embed_query(self, text):
        emb = np.array(self.embed_documents([text]))
        return emb[0]

