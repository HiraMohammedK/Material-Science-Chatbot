# multi-task model
class MultiTaskMatSciBERT(BertPreTrainedModel):
    def __init__(self, config):
        super().__init__(config)
        self.bert = BertModel(config)
        hidden = config.hidden_size
        self.reg_heads = nn.ModuleList([nn.Linear(hidden, 1) for _ in continuous])
        self.cls_heads = nn.ModuleList([nn.Linear(hidden, 2) for _ in categorical])
        self.dropout = nn.Dropout(config.hidden_dropout_prob)
        self.init_weights()

    def forward(self, input_ids, attention_mask, labels=None):
        out = self.bert(input_ids=input_ids, attention_mask=attention_mask)
        pooled = self.dropout(out.pooler_output)

        # Predictions
        cont_preds = [h(pooled).squeeze(-1) for h in self.reg_heads]
        cat_preds = [h(pooled) for h in self.cls_heads]

        loss = None
        if labels is not None:
            labels = torch.tensor(labels, dtype=torch.float32, device=pooled.device)
            cont_labels = labels[:, : len(continuous)]
            cat_labels = labels[:, len(continuous) :].long()

            # Compute losses
            losses = []
            for i, pred in enumerate(cont_preds):
                losses.append(nn.MSELoss()(pred, cont_labels[:, i]))
            for i, pred in enumerate(cat_preds):
                losses.append(nn.CrossEntropyLoss()(pred, cat_labels[:, i]))
            loss = sum(losses) / len(losses)

        # Return in HF format
        return {
            "loss": loss,
            "logits": (torch.stack(cont_preds, dim=1), torch.stack([p for p in cat_preds], dim=1))
        }
model = MultiTaskMatSciBERT.from_pretrained(model_name)

